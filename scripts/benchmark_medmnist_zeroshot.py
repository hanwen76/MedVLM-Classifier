#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import torch
from PIL import Image
from tqdm import tqdm

# Allow running this script directly without setting PYTHONPATH manually.
PROJECT_ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = PROJECT_ROOT / "src"
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from medvlm_classifier.model.factory import load_model_and_processor_by_id


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Zero-shot MedMNIST classification benchmark for VLMs (no finetuning)."
    )
    parser.add_argument(
        "--model_ids",
        type=str,
        required=True,
        help="Comma-separated model ids, e.g. llava-hf/llava-1.5-7b-hf,microsoft/llava-med-v1.5-mistral-7b",
    )
    parser.add_argument(
        "--data_json",
        type=str,
        required=True,
        help="Path to MedMNIST split json, e.g. data/medmnist/pathmnist/test.json",
    )
    parser.add_argument(
        "--image_root",
        type=str,
        required=True,
        help="Image directory, e.g. data/medmnist/pathmnist/images",
    )
    parser.add_argument(
        "--labels_json",
        type=str,
        required=True,
        help="Path to labels.json generated by prepare_medmnist.py",
    )
    parser.add_argument("--batch_size", type=int, default=1)
    parser.add_argument("--max_new_tokens", type=int, default=16)
    parser.add_argument(
        "--language",
        type=str,
        default="en",
        choices=["en", "zh"],
        help="Prompt language.",
    )
    parser.add_argument(
        "--mode",
        type=str,
        default="choice",
        choices=["choice", "free"],
        help="choice: include class list in prompt; free: open answer",
    )
    parser.add_argument(
        "--max_samples",
        type=int,
        default=0,
        help="0 means evaluate all samples",
    )
    parser.add_argument(
        "--output_dir",
        type=str,
        default="outputs/medmnist_zeroshot",
    )
    return parser.parse_args()


def load_json(path: str | Path):
    with Path(path).open("r", encoding="utf-8") as f:
        return json.load(f)


def _configure_llava_processor(processor, model) -> None:
    # Forward-compatible fix for LLaVA image token expansion in recent transformers.
    cfg = getattr(model, "config", None)
    vision_cfg = getattr(cfg, "vision_config", None)
    patch_size = getattr(vision_cfg, "patch_size", None)
    select_strategy = getattr(cfg, "vision_feature_select_strategy", None)
    if patch_size is not None and not hasattr(processor, "patch_size"):
        processor.patch_size = patch_size
    if select_strategy is not None and not hasattr(processor, "vision_feature_select_strategy"):
        processor.vision_feature_select_strategy = select_strategy


def _pick_reference_dtype(model) -> torch.dtype | None:
    for name, p in model.named_parameters():
        if not p.is_floating_point():
            continue
        if "vision_tower" in name:
            return p.dtype

    counts: dict[torch.dtype, int] = {}
    for _, p in model.named_parameters():
        if not p.is_floating_point():
            continue
        counts[p.dtype] = counts.get(p.dtype, 0) + p.numel()
    if not counts:
        return None
    return max(counts.items(), key=lambda x: x[1])[0]


def _align_projector_dtype(model) -> None:
    target_dtype = _pick_reference_dtype(model)
    if target_dtype is None:
        return

    for attr in ("multi_modal_projector", "mm_projector", "projector"):
        module = getattr(model, attr, None)
        if module is not None:
            module.to(dtype=target_dtype)
            print(f"[eval] aligned {attr} dtype to {target_dtype}")
            return

    for name, module in model.named_modules():
        if name.endswith(("multi_modal_projector", "mm_projector", "projector")):
            module.to(dtype=target_dtype)
            print(f"[eval] aligned {name} dtype to {target_dtype}")
            return


def ordered_labels(labels_map: dict) -> list[str]:
    pairs: list[tuple[int, str]] = []
    for k, v in labels_map.items():
        pairs.append((int(k), str(v)))
    pairs.sort(key=lambda x: x[0])
    return [x[1] for x in pairs]


def build_question(labels: list[str], mode: str, language: str) -> str:
    if language == "zh":
        if mode == "choice":
            return f"请判断这张医学图像属于哪个类别？请只输出一个类别名。可选类别：{', '.join(labels)}"
        return "请判断这张医学图像的类别，并只输出类别名称。"

    if mode == "choice":
        return f"What is the class of this medical image? Output exactly one class name from: {', '.join(labels)}"
    return "What is the class of this medical image? Output only the class name."


def build_prompt(model_id: str, question: str) -> str:
    model_id_l = model_id.lower()

    if "llava-v1.6-mistral" in model_id_l:
        return f"[INST] <image>\\n{question}[/INST]"
    if "llava-v1.6-vicuna" in model_id_l:
        return (
            "A chat between a curious human and an artificial intelligence assistant. "
            "The assistant gives helpful, detailed, and polite answers to the human's questions. "
            f"USER: <image>\\n{question} ASSISTANT:"
        )
    if "blip" in model_id_l:
        return f"Question: {question} Answer:"
    return f"USER: <image>\\n{question}\\nASSISTANT:"


def is_qwen2_vl(model_id: str) -> bool:
    mid = model_id.lower()
    return "qwen2-vl" in mid or "qwen-vl" in mid


def build_qwen2_vl_inputs(processor, images: list[Image.Image], question: str):
    texts: list[str] = []
    for _ in images:
        messages = [
            {
                "role": "user",
                "content": [
                    {"type": "image"},
                    {"type": "text", "text": question},
                ],
            }
        ]
        text = processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        texts.append(text)
    return processor(text=texts, images=images, padding=True, return_tensors="pt")


def clean_pred(model_id: str, text: str) -> str:
    model_id_l = model_id.lower()
    if "mistral" in model_id_l:
        return text.split("[/INST]")[-1].strip()
    if "blip" in model_id_l:
        return text.split("Answer:")[-1].strip()
    return text.split("ASSISTANT:")[-1].strip()


def extract_label(pred: str, labels: list[str]) -> str | None:
    pred_l = pred.lower()
    # Longest-first to reduce partial collisions.
    for label in sorted(labels, key=len, reverse=True):
        if label.lower() in pred_l:
            return label

    # Fallback exact token match (case-insensitive)
    for token in pred.replace("\n", " ").split():
        token_l = token.strip(" ,.;:!?\"'()[]{}")
        for label in labels:
            if token_l.lower() == label.lower():
                return label

    return None


def evaluate_one_model(
    model_id: str,
    rows: list[dict],
    image_root: Path,
    labels: list[str],
    batch_size: int,
    max_new_tokens: int,
    language: str,
    mode: str,
    output_dir: Path,
) -> dict:
    dtype = torch.bfloat16 if torch.cuda.is_available() else torch.float32
    model, processor = load_model_and_processor_by_id(model_id, torch_dtype=dtype)
    _configure_llava_processor(processor, model)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model.to(device)
    _align_projector_dtype(model)
    model.eval()

    question = build_question(labels=labels, mode=mode, language=language)
    prompt_template = build_prompt(model_id, question)

    pred_rows: list[dict] = []
    correct = 0

    for i in tqdm(range(0, len(rows), batch_size), desc=f"eval-{model_id}"):
        batch = rows[i : i + batch_size]
        images = [Image.open(image_root / item["image"]).convert("RGB") for item in batch]
        if is_qwen2_vl(model_id):
            inputs = build_qwen2_vl_inputs(processor=processor, images=images, question=question)
        else:
            prompts = [prompt_template for _ in batch]
            inputs = processor(text=prompts, images=images, padding=True, return_tensors="pt")
        inputs = {k: v.to(device) for k, v in inputs.items()}

        with torch.no_grad():
            output = model.generate(**inputs, max_new_tokens=max_new_tokens)
        generated_text = processor.batch_decode(output, skip_special_tokens=True)

        for item, text in zip(batch, generated_text):
            pred_text = clean_pred(model_id=model_id, text=text)
            pred_label = extract_label(pred_text, labels)
            gt = item["label"]
            is_correct = pred_label == gt
            if is_correct:
                correct += 1

            pred_rows.append(
                {
                    "image": item["image"],
                    "label": gt,
                    "pred_text": pred_text,
                    "pred_label": pred_label,
                    "is_correct": is_correct,
                }
            )

    total = len(rows)
    acc = correct / max(total, 1)
    result = {
        "model_id": model_id,
        "accuracy": acc,
        "correct": correct,
        "total": total,
        "mode": mode,
        "language": language,
        "question": question,
    }

    safe_name = model_id.replace("/", "__")
    pred_path = output_dir / f"{safe_name}.predictions.jsonl"
    with pred_path.open("w", encoding="utf-8") as f:
        for row in pred_rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    summary_path = output_dir / f"{safe_name}.summary.json"
    summary_path.write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
    return result


def main() -> None:
    args = parse_args()

    rows = load_json(args.data_json)
    if args.max_samples > 0:
        rows = rows[: args.max_samples]

    labels_map = load_json(args.labels_json)
    labels = ordered_labels(labels_map)

    image_root = Path(args.image_root)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    model_ids = [x.strip() for x in args.model_ids.split(",") if x.strip()]

    all_results = []
    for model_id in model_ids:
        res = evaluate_one_model(
            model_id=model_id,
            rows=rows,
            image_root=image_root,
            labels=labels,
            batch_size=args.batch_size,
            max_new_tokens=args.max_new_tokens,
            language=args.language,
            mode=args.mode,
            output_dir=output_dir,
        )
        print(f"[result] {model_id}: acc={res['accuracy']:.4f} ({res['correct']}/{res['total']})")
        all_results.append(res)
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    leaderboard = sorted(all_results, key=lambda x: x["accuracy"], reverse=True)
    (output_dir / "leaderboard.json").write_text(
        json.dumps(leaderboard, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    print("[done] leaderboard saved to", output_dir / "leaderboard.json")


if __name__ == "__main__":
    main()
